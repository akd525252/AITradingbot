-- !! STEP 0 — REQUIRED: Create exec_sql helper function !!
CREATE OR REPLACE FUNCTION public.exec_sql(query_text TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  result JSONB;
  upper_query TEXT;
BEGIN
  upper_query := ltrim(upper(query_text));
  IF upper_query LIKE 'SELECT%' OR upper_query LIKE 'WITH%' OR upper_query LIKE 'SHOW%' OR upper_query LIKE 'EXPLAIN%' THEN
    EXECUTE 'SELECT jsonb_agg(row_to_json(t)) FROM (' || query_text || ') t' INTO result;
    RETURN COALESCE(result, '[]'::JSONB);
  ELSIF (upper_query LIKE 'INSERT%' OR upper_query LIKE 'UPDATE%' OR upper_query LIKE 'DELETE%') AND upper_query LIKE '%RETURNING%' THEN
    EXECUTE 'WITH affected_rows AS (' || query_text || ') SELECT jsonb_agg(row_to_json(t)) FROM affected_rows t' INTO result;
    RETURN COALESCE(result, '[]'::JSONB);
  ELSE
    EXECUTE query_text;
    RETURN '[]'::JSONB;
  END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION public.exec_sql(TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.exec_sql(TEXT) TO anon;
GRANT EXECUTE ON FUNCTION public.exec_sql(TEXT) TO authenticated;

