-- TABLE 1: USERS
-- ==========================================
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) UNIQUE NOT NULL,
  email VARCHAR(255) UNIQUE,
  phone_number VARCHAR(50),
  full_name VARCHAR(255),
  profile_pic TEXT,
  credit_score NUMERIC(5,2) DEFAULT 100.0,
  withdraw_enabled INTEGER DEFAULT 1 CHECK(withdraw_enabled IN (0, 1)),
  withdraw_limit NUMERIC(15,2) DEFAULT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(50) DEFAULT 'user' CHECK(role IN ('admin', 'employee', 'user')),
  balance NUMERIC(15,2) DEFAULT 0.0,
  demo_balance NUMERIC(15,2) DEFAULT 10000.0,
  status VARCHAR(50) DEFAULT 'active' CHECK(status IN ('active', 'frozen', 'blocked')),
  invite_code VARCHAR(100) UNIQUE,
  invited_by_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  real_account_active INTEGER DEFAULT 0 CHECK(real_account_active IN (0, 1)),
  kyc_status VARCHAR(50) DEFAULT 'unverified' CHECK(kyc_status IN ('unverified', 'pending', 'verified', 'rejected')),
  kyc_country VARCHAR(100),
  kyc_address TEXT,
  kyc_document_front TEXT,
  kyc_document_back TEXT,
  kyc_selfie TEXT,
  kyc_submitted_at VARCHAR(100),
  kyc_rejected_reason TEXT,
  currency VARCHAR(10) DEFAULT 'USD',
  is_test BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

